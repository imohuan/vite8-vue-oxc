import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const publicDir = path.join(projectRoot, "dist");
const outputFile = path.join(projectRoot, "src", "servers", "public-assets.ts");

const mimeByExt = new Map([
  [".html", "text/html; charset=utf-8"],
  [".htm", "text/html; charset=utf-8"],
  [".js", "application/javascript; charset=utf-8"],
  [".mjs", "application/javascript; charset=utf-8"],
  [".css", "text/css; charset=utf-8"],
  [".json", "application/json; charset=utf-8"],
  [".svg", "image/svg+xml"],
  [".png", "image/png"],
  [".jpg", "image/jpeg"],
  [".jpeg", "image/jpeg"],
  [".gif", "image/gif"],
  [".ico", "image/x-icon"],
  [".webp", "image/webp"],
  [".txt", "text/plain; charset=utf-8"],
  [".map", "application/json; charset=utf-8"],
  [".woff", "font/woff"],
  [".woff2", "font/woff2"],
  [".ttf", "font/ttf"],
]);

function toPosix(p) {
  return p.replace(/\\/g, "/");
}

async function walk(dir, base = dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(abs, base)));
      continue;
    }
    if (entry.isFile()) {
      files.push(path.relative(base, abs));
    }
  }

  return files;
}

function mimeType(file) {
  return mimeByExt.get(path.extname(file).toLowerCase()) ?? "application/octet-stream";
}

async function main() {
  const relativeFiles = await walk(publicDir);
  const rows = [];

  for (const rel of relativeFiles) {
    const abs = path.join(publicDir, rel);
    const buf = await readFile(abs);
    const routePath = `/${toPosix(rel)}`;
    const encoded = buf.toString("base64");
    rows.push(
      `  ${JSON.stringify(routePath)}: { contentType: ${JSON.stringify(mimeType(rel))}, contentBase64: ${JSON.stringify(encoded)} },`,
    );
  }

  const source = `/* eslint-disable */\n// Auto-generated by tools/generate-public-assets.mjs. Do not edit manually.\n\nexport interface PublicAsset {\n  contentType: string;\n  contentBase64: string;\n}\n\nexport const PUBLIC_ASSETS: Record<string, PublicAsset> = {\n${rows.join("\n")}\n};\n`;

  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, source, "utf8");

  console.info(`Generated ${relativeFiles.length} public assets -> ${outputFile}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
